//! Cross-validation of `BaryonicPipeline::evolve` against the code it
//! is a port of.
//!
//! The expected values below are **measurements of the committed
//! Cython**, not snapshots of the Rust: they are produced by
//! `Scripts/Validation/reference_baryonic.py`, which drives
//! `Functions_c.pyx::Starformation_c` itself on this exact fixture, fed
//! the Rust's own `age(z)` grid so the comparison isolates the baryonic
//! pipeline from the cosmology port (validated separately in M2).
//!
//! # The one place the two deliberately disagree
//!
//! `Functions.py::StarFormation` computes the gas ceiling as
//! `MaxGas = np.power(10, GetGasMass(...))` — a **linear** mass in Msun,
//! of order 4e9 — and `Starformation_c` then tests it as
//!
//! ```text
//! if SM_new > 0:
//!     if c_log10(SM_new) > MaxGas[k]:   # log10 compared against ~4e9
//!         SFR = c_pow(10, M_out[k,i]-12.0)
//! ```
//!
//! `log10(SM_new)` cannot exceed ~12 for any physical stellar mass, so
//! the test is never true and **the gas supply never limits star
//! formation in the Python**. The whole `GetGasMass`/`GetMaxGasMass`
//! machinery is inert. (`Starformation_c` also uses `MaxGas` *linearly*
//! four lines earlier, when filling its unused `GasMass` array, so it
//! contradicts itself within one function.)
//!
//! The Rust keeps the ceiling in log throughout and the cap engages, as
//! intended. So the tests here come in two parts: with the cap
//! neutralised the two implementations agree to ~1e-9 step for step,
//! which validates the port; with it live the Rust suppresses growth,
//! which is the intended physics. See `docs/PORT_CORRECTIONS.md` A6.

use rand::rngs::StdRng;
use rand::RngCore;
use rand::SeedableRng;

use steel_core::baryonic::{BaryonicPipeline, SatelliteState, Timeline};
use steel_core::cosmology::Cosmology;
use steel_core::gas::GasMassModel;
use steel_plugins::{Cattaneo11, Planck15, StewartScaling, TomczakFormSfr, Wetzel13};

/// A gas model with no ceiling, reproducing the Python's dead cap so
/// the rest of the pipeline can be compared step for step.
struct UncappedGas;

impl GasMassModel for UncappedGas {
    fn max_gas_mass(&self, _log_halo_mass: f64) -> f64 {
        f64::INFINITY
    }
    fn gas_mass(&self, _log_sfr: f64, _log_halo_mass: f64, _rng: Option<&mut dyn RngCore>) -> f64 {
        f64::INFINITY
    }
}

fn build_timeline(cosmo: &Planck15) -> Timeline {
    let z: Vec<f64> = (0..11).map(|i| 1.0 - i as f64 * 0.05).collect();
    let t: Vec<f64> = z.iter().map(|&zi| cosmo.age(zi)).collect();
    let mut dt: Vec<f64> = t.windows(2).map(|w| w[1] - w[0]).collect();
    dt.push(*dt.last().unwrap());
    // `t_dyn_friction` must exceed the timeline's own span (2.74 Gyr
    // here), otherwise the fixture describes a satellite still infalling
    // past its own merger timescale — which the real pipeline never
    // produces (for mergers the window *is* the dynamical friction time;
    // for survivors it is shorter) and which the Python reference has no
    // notion of, since `StellarMassLoss`'s `Factor` is <= 1 by
    // construction there.
    Timeline { z, t, dt, log_host_mass: vec![13.0; 11], t_dyn_friction: 3.0 }
}

fn build_pipeline(cosmo: &Planck15) -> BaryonicPipeline {
    BaryonicPipeline::new(
        Box::new(TomczakFormSfr::ce()),
        Box::new(Wetzel13::new()),
        Box::new(StewartScaling::from_cosmology(cosmo)),
        Box::new(Cattaneo11),
    )
}

fn build_uncapped_pipeline() -> BaryonicPipeline {
    BaryonicPipeline::new(
        Box::new(TomczakFormSfr::ce()),
        Box::new(Wetzel13::new()),
        Box::new(UncappedGas),
        Box::new(Cattaneo11),
    )
}

fn build_galaxy(z0: f64) -> SatelliteState {
    SatelliteState {
        log_sm_infall: 10.0,
        log_host_mass_infall: 13.0,
        log_sat_mass_infall: 11.5,
        z_infall: z0,
        pre_quenched: false,
    }
}

fn assert_matches(history: &[f64], expected: &[f64], tol: f64) {
    assert_eq!(
        history.len(),
        expected.len(),
        "trajectory length changed -- the regression values no longer describe the whole output"
    );
    for (i, (&got, &want)) in history.iter().zip(expected.iter()).enumerate() {
        assert!((got - want).abs() < tol, "step {i}: got {got}, want {want}");
    }
}

