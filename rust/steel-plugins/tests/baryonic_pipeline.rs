#[test]
fn unstripped_noiseless_trajectory_matches_the_cython_when_the_gas_cap_is_neutralised() {
    let cosmo = Planck15::new();
    let timeline = build_timeline(&cosmo);
    let galaxy = build_galaxy(timeline.z[0]);
    let pipeline = build_uncapped_pipeline();

    let mut rng = StdRng::seed_from_u64(1);
    let history = pipeline.evolve(&galaxy, &timeline, false, false, &mut rng);
    assert_matches(&history.log_sm, &PYTHON_UNSTRIPPED, 1e-8);
}

/// The stripped trajectory matches the Cython *with the real gas model
/// in place*, because a satellite losing mass never accumulates enough
/// newly-formed stars to hit the ceiling. That it agrees to 1e-9 over
/// all eleven steps with no adjustment is the cleanest single check
/// that the port is faithful.
#[test]
fn stripped_noiseless_trajectory_matches_the_cython_exactly() {
    let cosmo = Planck15::new();
    let timeline = build_timeline(&cosmo);
    let galaxy = build_galaxy(timeline.z[0]);
    let pipeline = build_pipeline(&cosmo);

    let mut rng = StdRng::seed_from_u64(1);
    let history = pipeline.evolve(&galaxy, &timeline, true, false, &mut rng);
    assert_matches(&history.log_sm, &PYTHON_STRIPPED, 1e-8);
}

/// PORT-FIX A6: the gas supply actually limits star formation here,
/// where in the Python it never can. This pins the Rust's own behaviour
/// so the correction cannot silently revert.
#[test]
fn the_gas_supply_cap_engages_and_suppresses_growth() {
    let cosmo = Planck15::new();
    let timeline = build_timeline(&cosmo);
    let galaxy = build_galaxy(timeline.z[0]);

    let mut rng = StdRng::seed_from_u64(1);
    let capped = build_pipeline(&cosmo).evolve(&galaxy, &timeline, false, false, &mut rng);
    let mut rng = StdRng::seed_from_u64(1);
    let uncapped = build_uncapped_pipeline().evolve(&galaxy, &timeline, false, false, &mut rng);

    // The two agree until the galaxy has formed enough new stars to
    // exhaust its gas, then diverge.
    for i in 0..=6 {
        assert!(
            (capped.log_sm[i] - uncapped.log_sm[i]).abs() < 1e-12,
            "step {i}: the cap should not have engaged yet"
        );
    }
    assert!(
        *capped.log_sm.last().unwrap() < *uncapped.log_sm.last().unwrap() - 0.01,
        "the gas cap should measurably suppress final mass: {} vs {}",
        capped.log_sm.last().unwrap(),
        uncapped.log_sm.last().unwrap()
    );

    let expected = [
        10.0000000000,
        10.0278564415,
        10.0552312867,
        10.0825115484,
        10.1098555718,
        10.1373443940,
        10.1639858895,
        10.1614012460,
        10.1595470425,
        10.1580638038,
        10.1568146930,
    ];
    assert_matches(&capped.log_sm, &expected, 1e-8);
}

#[test]
fn stripped_satellite_ends_lower_mass_than_unstripped() {
    let cosmo = Planck15::new();
    let timeline = build_timeline(&cosmo);
    let galaxy = build_galaxy(timeline.z[0]);
    let pipeline = build_pipeline(&cosmo);

    let mut rng_a = StdRng::seed_from_u64(1);
    let unstripped = pipeline.evolve(&galaxy, &timeline, false, false, &mut rng_a);
    let mut rng_b = StdRng::seed_from_u64(1);
    let stripped = pipeline.evolve(&galaxy, &timeline, true, false, &mut rng_b);

    assert!(*stripped.log_sm.last().unwrap() < *unstripped.log_sm.last().unwrap());
}

#[test]
fn scatter_on_gives_reproducible_results_for_a_fixed_seed() {
    let cosmo = Planck15::new();
    let timeline = build_timeline(&cosmo);
    let galaxy = build_galaxy(timeline.z[0]);
    let pipeline = build_pipeline(&cosmo);

    let mut rng1 = StdRng::seed_from_u64(99);
    let h1 = pipeline.evolve(&galaxy, &timeline, false, true, &mut rng1);
    let mut rng2 = StdRng::seed_from_u64(99);
    let h2 = pipeline.evolve(&galaxy, &timeline, false, true, &mut rng2);

    // Exact equality is deliberate here, not an oversight. The claim
    // under test is specifically that an identical seed reproduces
    // bit-identical output -- same process, same code path, same
    // deterministic IEEE operations. Comparing within an epsilon would
    // weaken this into "roughly similar", which is no longer a
    // determinism test at all.
    assert_eq!(h1.log_sm, h2.log_sm);
}

/// With scatter off the gas ceiling must be the relation's mean, not a
/// draw -- otherwise "deterministic mode" still has one live stochastic
/// source and the three-way comparison's strong claim is unfounded.
#[test]
fn noiseless_evolution_does_not_consume_randomness() {
    let cosmo = Planck15::new();
    let timeline = build_timeline(&cosmo);
    let galaxy = build_galaxy(timeline.z[0]);
    let pipeline = build_pipeline(&cosmo);

    let mut rng_a = StdRng::seed_from_u64(1);
    let a = pipeline.evolve(&galaxy, &timeline, false, false, &mut rng_a);
    let mut rng_b = StdRng::seed_from_u64(12345);
    let b = pipeline.evolve(&galaxy, &timeline, false, false, &mut rng_b);

    assert_eq!(a.log_sm, b.log_sm, "a noiseless run must not depend on the seed");
}
